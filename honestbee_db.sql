CREATE TABLE IF NOT EXISTS customer (
  CUST_id VARCHAR(120) NOT NULL PRIMARY KEY,
  CUST_firstName VARCHAR(80) DEFAULT NULL,
  CUST_lastName VARCHAR(80) DEFAULT NULL,
  CUST_email VARCHAR(190) DEFAULT NULL,
  CUST_password VARCHAR(255) DEFAULT NULL,
  CUST_role VARCHAR(40) NOT NULL DEFAULT 'customer',
  CUST_status VARCHAR(40) NOT NULL DEFAULT 'Active',
  CUST_phone VARCHAR(20) DEFAULT NULL,
  CUST_city VARCHAR(80) DEFAULT NULL,
  CUST_address TEXT DEFAULT NULL,
  CUST_preferredDeliveryTime VARCHAR(60) DEFAULT NULL,
  CUST_createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CUST_updatedAt DATETIME DEFAULT NULL,
  INDEX idx_customer_email (CUST_email),
  INDEX idx_customer_status (CUST_status),
  INDEX idx_customer_city (CUST_city),
  CONSTRAINT fk_customer_city FOREIGN KEY (CUST_city) REFERENCES service_city (CITY_name)
    ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

