CREATE TABLE IF NOT EXISTS admin (
  ADMIN_id VARCHAR(120) NOT NULL PRIMARY KEY,
  ADMIN_email VARCHAR(190) NOT NULL UNIQUE,
  ADMIN_password VARCHAR(255) NOT NULL,
  ADMIN_fullName VARCHAR(190) DEFAULT NULL,
  ADMIN_status VARCHAR(40) NOT NULL DEFAULT 'Active',
  ADMIN_createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

